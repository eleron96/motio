-- Язык профиля перестаёт быть принудительно английским.
--
-- Раньше колонка была `not null default 'en'`, поэтому у КАЖДОГО нового
-- пользователя в базе оказывался английский — неотличимо от осознанного
-- выбора. Из-за этого приложение не могло угадать язык по браузеру: даже
-- определив русский, оно тут же перезатирало его дефолтом из профиля.
--
-- Теперь новый профиль рождается с NULL = «пользователь ещё не выбирал».
-- Приложение при первом входе подставляет язык браузера и записывает его сюда.
-- Существующие строки не трогаем: их 'en'/'ru' — это уже состоявшийся выбор.

alter table public.profiles
  alter column locale drop default;

alter table public.profiles
  alter column locale drop not null;

-- Констрейнт остаётся прежним: NULL проверку проходит (unknown), так что
-- допустимые значения по-прежнему только 'en' и 'ru'.
